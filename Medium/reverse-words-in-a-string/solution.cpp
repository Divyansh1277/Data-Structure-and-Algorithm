class Solution {
public:
    string reverseWords(string s) {
        vector<string> v;
        int size = s.size();
        for(int i = 0;i<size();i++){
            string s1 = "";
            if(s[i]==' ') v.push_back(s1);
        }
        for(int i = 0;i<size();i++){
            cout<<v[i]<<" ";
        }
        return s;
    }
};